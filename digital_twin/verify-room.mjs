import {chromium,expect} from '@playwright/test';
import fs from 'node:fs';
import {fileURLToPath} from 'node:url';
process.chdir(fileURLToPath(new URL('.',import.meta.url)));
const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',args:['--enable-unsafe-swiftshader']});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[],failed=[],actions=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('response',r=>{if(r.status()>=400)failed.push(new URL(r.url()).pathname+' '+r.status());});
page.on('request',r=>{if(r.url().endsWith('/api/action'))actions.push(r.postDataJSON());});
try{
 await page.goto(JSON.parse(fs.readFileSync('../studio_runtime.json','utf8')).url);
 await page.waitForFunction(()=>window.studioDebug,null,{timeout:90000});
 await expect(page.locator('#fullToolbar')).toBeHidden();
 expect(await page.evaluate(()=>!!window.studioDebug.environment.room.getObjectByName('Official Finstein logo'))).toBe(true);
 const pose=await page.evaluate(()=>({angles:window.studioDebug.targets,camera:window.studioDebug.camera.position.toArray()}));
 await page.locator('#expandView').click();
 await expect(page.locator('#backToStudio')).toBeFocused();
 await expect(page.locator('#fullEmergency')).toBeVisible();
 await expect(page.locator('#fullEmergency')).toBeDisabled();
 await page.waitForTimeout(800);
 expect(await page.locator('#viewport').boundingBox()).toEqual({x:0,y:0,width:1440,height:1000});
 expect(await page.evaluate(()=>document.querySelector('.inspector').inert)).toBe(true);
 expect(await page.evaluate(()=>window.studioDebug.targets)).toEqual(pose.angles);
 expect(await page.evaluate(()=>window.studioDebug.camera.position.toArray())).toEqual(pose.camera);
 await page.screenshot({path:'cabin-full.png'});
 await page.keyboard.press('Shift+Tab');
 await expect(page.locator('#openWall')).toBeFocused();
 await page.keyboard.press('Tab');
 await expect(page.locator('#backToStudio')).toBeFocused();
 await page.locator('[data-room-view=desk]').click();
 await page.waitForTimeout(500);
 await page.screenshot({path:'cabin-desk.png'});
 await page.locator('#backToStudio').click();
 await expect(page.locator('#expandView')).toBeFocused();
 expect(await page.evaluate(()=>document.querySelector('.inspector').inert)).toBe(false);
 await page.locator('#expandView').click();
 await page.keyboard.press('Escape');
 await expect(page.locator('#fullToolbar')).toBeHidden();
 await page.locator('[data-view=inside]').click();
 await page.screenshot({path:'cabin-studio.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.locator('#expandView').click();
 await page.locator('[data-room-view=room]').click();
 await page.waitForTimeout(500);
 expect(await page.locator('#viewport').boundingBox()).toEqual({x:0,y:0,width:390,height:844});
 await expect(page.locator('#backToStudio')).toBeInViewport();
 await expect(page.locator('#fullEmergency')).toBeInViewport();
 await page.screenshot({path:'cabin-mobile-full.png'});
 await page.locator('#backToStudio').click();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 expect(actions).toHaveLength(0);
 // Exercise the full-view emergency affordance with mocked telemetry and POSTs.
 const mock=await page.evaluate(()=>structuredClone(window.studioDebug.state));
 Object.assign(mock,{ready:true,busy:true});
 await page.route('**/api/action',route=>route.fulfill({json:mock}));
 await page.route('**/api/state',route=>route.fulfill({json:mock}));
 await page.locator('#expandView').click();
 await expect(page.locator('#fullEmergency')).toBeEnabled();
 await page.keyboard.press('Escape');
 expect(actions).toHaveLength(0);
 await page.locator('#expandView').click();
 await page.locator('#fullEmergency').click();
 await expect.poll(()=>actions.length).toBe(1);
 expect(actions[0].action).toBe('emergency');
 expect(errors).toHaveLength(0);
 expect(failed).toHaveLength(0);
 console.log('PASS: authentic logo, room loaded, full-view sizing, focus containment/restoration, pose preservation, camera presets, Back/Escape, mobile layout, mocked emergency action, zero actual hardware commands, zero failed resources.');
}finally{await browser.close();}
